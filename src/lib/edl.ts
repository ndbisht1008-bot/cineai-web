// The edit decision list and credits: pure data, no media code (loads instantly).
import { shotDuration, type Project, type Shot, type Transition } from "./model";

export interface Segment { shot: Shot; clipBlobId: string; start: number; end: number; inSec: number; clipDur: number; transitionOut: Transition; subtitle: string }

/** The edit decision list: where each shot sits on the timeline and which part of which clip it shows. */
export function timeline(p: Project): Segment[] {
  const byId = new Map(p.shots.map((s) => [s.id, s]));
  let t = 0;
  return p.shots.map((s) => {
    const owner = s.reuseOf ? byId.get(s.reuseOf) : s;
    const clip = owner?.clip;
    if (!clip) throw new Error(`Shot ${p.shots.indexOf(s) + 1} has no clip yet.`);
    const dur = p.kind === "music" ? shotDuration(s) : clip.durationSec;
    const start = p.kind === "music" ? s.startSec! : t;
    t = start + dur;
    return { shot: s, clipBlobId: clip.blobId, start, end: start + dur, inSec: s.clipInSec ?? 0, clipDur: clip.durationSec, transitionOut: s.transition,
      subtitle: p.kind === "movie" && p.subtitles ? s.narration : "" };
  });
}

/** Plain-text credits: which clip came from where, with its motion check. */
export function credits(p: Project): string {
  const lines = [`${p.name}`, `Made with CineAI Studio (web), ${new Date().toISOString().slice(0, 10)}`, ""];
  const seen = new Set<string>();
  p.shots.forEach((s, i) => {
    const c = s.reuseOf ? p.shots.find((x) => x.id === s.reuseOf)?.clip : s.clip;
    if (!c || seen.has(c.blobId)) return;
    seen.add(c.blobId);
    const src = c.source === "generated" ? `AI-generated by ${c.provider} (${c.model}), ${c.mode === "i2v" ? "image-to-video" : "text-to-video"}, seed ${c.seed}`
      : c.source === "imported-flow" ? "Imported by the user from Google Flow (not generated by CineAI)" : "Imported by the user from their own file (not generated by CineAI)";
    lines.push(`Shot ${i + 1}: ${src}. Motion check: ${c.motion.verdict} (${Math.round(c.motion.movingPairs * 100)} % of frame pairs move).`);
    if (c.source === "generated") lines.push(`  Prompt: ${c.prompt}`);
  });
  if (p.kind === "music" && p.songName) lines.push("", `Music: ${p.songName} (uploaded by the user)`);
  return lines.join("\n");
}
