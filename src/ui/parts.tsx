export function Thumb({ blobId, className = "h-16 w-12" }: { blobId?: string; className?: string }) {
  const url = useBlobUrl(blobId);
  return url ? <video src={url + "#t=0.5"} muted playsInline preload="metadata" className={`${className} shrink-0 rounded-md bg-black object-cover`} />
    : <div className={`${className} shrink-0 rounded-md bg-panel2`} />;
}

export function Tabs<T extends string>({ tabs, value, onChange }: { tabs: [T, string][]; value: T; onChange: (t: T) => void }) {
  return (
    <div role="tablist" className="flex gap-1 overflow-x-auto border-b border-line">
      {tabs.map(([id, label], i) => (
        <button key={id} role="tab" aria-selected={value === id} onClick={() => onChange(id)}
          className={`whitespace-nowrap border-b-2 px-3 py-2 text-sm font-medium ${value === id ? "border-accent text-text" : "border-transparent text-mute hover:text-text"}`}>
          <span className="mr-1.5 text-xs text-mute">{i + 1}</span>{label}
        </button>
      ))}
    </div>
  );
}

const STATUS: Record<Shot["status"], [string, string]> = {
  none: ["Not generated", "text-mute"], queued: ["Queued", "text-accent2"], generating: ["Generating…", "text-accent"],
  checking: ["Checking motion…", "text-accent"], done: ["AI clip ready", "text-ok"], failed: ["Failed", "text-bad"], rejected: ["Rejected", "text-bad"],
};

export function StatusBadge({ shot, owner }: { shot: Shot; owner?: Shot }) {
  if (shot.reuseOf) {
    const ok = owner?.clip?.motion.verdict === "real_motion";
    return <span className={`text-xs ${ok ? "text-ok" : "text-mute"}`}>Reuses shot {owner ? "clip" : "?"}{ok ? " ✓" : " (not generated yet)"}</span>;
  }
  const [t, c] = STATUS[shot.status];
  const src = shot.clip?.source;
  return <span className={`text-xs font-medium ${c}`}>{src && src !== "generated" && shot.status === "done" ? "Imported clip ready (not AI-generated by CineAI)" : t}</span>;
}

export function ShotCard(props: {
  project: Project; shot: Shot; index: number; busy: boolean;
  onChange: (fn: (s: Shot) => void) => void; onMove?: (dir: -1 | 1) => void; onDelete?: () => void; onRegenerate: () => void;
  onNudge?: (dir: -1 | 1) => void; extra?: ReactNode;
}) {
  const { project, shot, index, busy } = props;
  const owner = shot.reuseOf ? project.shots.find((s) => s.id === shot.reuseOf) : undefined;
  const clipId = (owner ?? shot).clip?.blobId;
  const url = useBlobUrl(clipId);
  const file = useRef<HTMLInputElement>(null);
  const [importSrc, setImportSrc] = useState<"imported-flow" | "imported-file">("imported-file");
  const [err, setErr] = useState("");
  const editable = !busy && shot.status !== "generating" && shot.status !== "checking";
  return (
    <li className="card grid gap-3 md:grid-cols-[180px_1fr]">
      <div>
        {url ? <video src={url} controls playsInline muted loop className={`w-full rounded-lg bg-black ${project.aspect === "9:16" ? "aspect-[9/16]" : "aspect-video"} object-cover`} />
          : <div className={`grid w-full place-items-center rounded-lg border border-dashed border-line bg-ink text-xs text-mute ${project.aspect === "9:16" ? "aspect-[9/16]" : "aspect-video"}`}>No clip</div>}
        {(owner ?? shot).clip && <p className="mt-1 text-[11px] leading-tight text-mute">
          {(owner ?? shot).clip!.source === "generated" ? `${(owner ?? shot).clip!.model}, ${(owner ?? shot).clip!.mode}` : (owner ?? shot).clip!.provider}
          {" · motion: "}{(owner ?? shot).clip!.motion.verdict.replace("_", " ")}</p>}
      </div>
      <div className="min-w-0 space-y-2">
        <div className="flex flex-wrap items-center gap-2">
          <b className="text-sm">Shot {index + 1}</b>
          {shot.section && <span className="chip">{shot.section}</span>}
          {shot.startSec !== undefined && <span className="chip">{shot.startSec.toFixed(2)}–{shot.endSec!.toFixed(2)} s</span>}
          {shot.continueFromPrevious && <span className="chip" title="Image-to-video from the previous shot's last frame">continues previous</span>}
          <StatusBadge shot={shot} owner={owner} />
          <div className="ml-auto flex gap-1">
            {props.onNudge && <><button className="btn-ghost !px-2 !py-1 text-xs" disabled={!editable || index === 0} title="Move this cut one beat earlier" onClick={() => props.onNudge!(-1)}>◀ beat</button>
              <button className="btn-ghost !px-2 !py-1 text-xs" disabled={!editable || index === 0} title="Move this cut one beat later" onClick={() => props.onNudge!(1)}>beat ▶</button></>}
            {props.onMove && <><button aria-label="Move up" className="btn-ghost !px-2 !py-1 text-xs" disabled={!editable || index === 0} onClick={() => props.onMove!(-1)}>↑</button>
              <button aria-label="Move down" className="btn-ghost !px-2 !py-1 text-xs" disabled={!editable || index === project.shots.length - 1} onClick={() => props.onMove!(1)}>↓</button></>}
            {props.onDelete && <button aria-label="Delete shot" className="btn-ghost !px-2 !py-1 text-xs" disabled={!editable} onClick={props.onDelete}>✕</button>}
          </div>
        </div>
        {shot.narration && <p className="font-[Noto_Sans_Devanagari] text-sm leading-relaxed">{shot.narration}</p>}
        <p className="text-xs text-mute">{shot.description}</p>
        {shot.error && <p className="rounded-md bg-bad/10 px-2 py-1 text-xs text-bad">{shot.error}</p>}
        {!shot.reuseOf && <>
          <label className="label" htmlFor={`p-${shot.id}`}>English video prompt (sent to the AI)</label>
          <textarea id={`p-${shot.id}`} className="field min-h-20 font-mono !text-xs" value={shot.prompt} disabled={!editable}
            onChange={(e) => props.onChange((s) => { s.prompt = e.target.value; })} />
          <div className="flex flex-wrap items-end gap-2">
            <div>
              <label className="label" htmlFor={`c-${shot.id}`}>Camera</label>
              <select id={`c-${shot.id}`} className="field !w-auto" value={shot.camera} disabled={!editable} onChange={(e) => props.onChange((s) => {
                const old = CAMERA_MOVES[s.camera], neu = CAMERA_MOVES[e.target.value as CameraMove];
                s.prompt = s.prompt.includes(old) ? s.prompt.replace(old, neu) : `${neu}, ${s.prompt}`; s.camera = e.target.value as CameraMove;
              })}>{Object.keys(CAMERA_MOVES).map((k) => <option key={k} value={k}>{k}</option>)}</select>
            </div>
            {project.kind === "movie" && <div>
              <label className="label" htmlFor={`d-${shot.id}`}>Clip seconds</label>
              <input id={`d-${shot.id}`} type="number" min={2} max={MAX_CLIP_SEC} step={0.5} className="field !w-20" value={shot.clipSec} disabled={!editable}
                onChange={(e) => props.onChange((s) => { s.clipSec = Math.min(MAX_CLIP_SEC, Math.max(2, +e.target.value || 2)); })} />
            </div>}
            <div>
              <label className="label" htmlFor={`t-${shot.id}`}>Transition out</label>
              <select id={`t-${shot.id}`} className="field !w-auto" value={shot.transition} disabled={!editable} onChange={(e) => props.onChange((s) => { s.transition = e.target.value as Transition; })}>
                {["cut", "crossfade", "fade-black", "flash"].map((t) => <option key={t}>{t}</option>)}
              </select>
            </div>
            {project.kind === "movie" && index > 0 && <label className="flex items-center gap-1.5 pb-2 text-xs">
              <input type="checkbox" checked={shot.continueFromPrevious} disabled={!editable} onChange={(e) => props.onChange((s) => { s.continueFromPrevious = e.target.checked; })} />
              Continue from previous shot
            </label>}
          </div>
          <div className="flex flex-wrap gap-2 pt-1">
            <button className="btn-ghost text-xs" disabled={!editable} onClick={props.onRegenerate}>{shot.clip ? "Regenerate" : "Generate"} this shot</button>
            <select aria-label="Import source" className="field !w-auto !py-1 text-xs" value={importSrc} onChange={(e) => setImportSrc(e.target.value as typeof importSrc)}>
              <option value="imported-file">My own clip</option><option value="imported-flow">Clip downloaded from Google Flow</option>
            </select>
            <button className="btn-ghost text-xs" disabled={!editable} onClick={() => file.current?.click()}>Import clip…</button>
            <input ref={file} type="file" accept="video/*" hidden onChange={async (e) => {
              const f = e.target.files?.[0]; e.target.value = ""; if (!f) return;
              setErr("");
              try { const { importClip } = await import("../lib/generate"); const copy = structuredClone(shot); await importClip(copy, f, importSrc); props.onChange((s) => Object.assign(s, copy)); }
              catch (x) { setErr((x as Error).message); }
            }} />
          </div>
          {err && <p className="text-xs text-bad">{err}</p>}
        </>}
        {props.extra}
      </div>
    </li>
  );
}

/** Waveform with sections, bars and the used range, drawn on a canvas. */
export function Waveform({ music, start, end, playhead }: { music: MusicAnalysis; start: number; end: number; playhead?: number }) {
  const ref = useRef<HTMLCanvasElement>(null);
  useEffect(() => {
    const c = ref.current; if (!c) return;
    const dpr = devicePixelRatio || 1, W = c.clientWidth, H = c.clientHeight;
    c.width = W * dpr; c.height = H * dpr;
    const g = c.getContext("2d")!; g.scale(dpr, dpr); g.clearRect(0, 0, W, H);
    const x = (t: number) => (t / music.durationSec) * W;
    const colors: Record<string, string> = { Intro: "#334155", Verse: "#1e3a5f", Chorus: "#7c4a03", Drop: "#7f1d1d", Breakdown: "#3b2f5c", Outro: "#334155" };
    for (const s of music.sections) { g.fillStyle = colors[s.label]; g.fillRect(x(s.startSec), 0, x(s.endSec) - x(s.startSec), H); g.fillStyle = "#cbd5e1"; g.font = "10px Inter"; g.fillText(s.label, x(s.startSec) + 3, 11); }
    g.fillStyle = "#e7eaf0";
    music.waveform.forEach((v, i) => { const px = (i / music.waveform.length) * W; const h = v * (H - 18) * 0.5; g.fillRect(px, H / 2 + 6 - h, Math.max(1, W / music.waveform.length - 0.5), 2 * h); });
    g.fillStyle = "rgba(245,165,36,0.9)"; for (const d of music.downbeats) g.fillRect(x(d), H - 5, 1, 5);
    g.fillStyle = "rgba(0,0,0,0.55)"; g.fillRect(0, 0, x(start), H); g.fillRect(x(end), 0, W - x(end), H);
    if (playhead !== undefined) { g.fillStyle = "#7cc4ff"; g.fillRect(x(playhead), 0, 2, H); }
  }, [music, start, end, playhead]);
  return <canvas ref={ref} className="h-28 w-full rounded-lg bg-ink" aria-label={`Waveform: ${music.sections.map((s) => s.label).join(", ")}`} />;
}
